BEGIN;

DROP TABLE IF EXISTS reviews      CASCADE;
DROP TABLE IF EXISTS payments     CASCADE;
DROP TABLE IF EXISTS order_items  CASCADE;
DROP TABLE IF EXISTS orders       CASCADE;
DROP TABLE IF EXISTS products     CASCADE;
DROP TABLE IF EXISTS suppliers    CASCADE;
DROP TABLE IF EXISTS categories   CASCADE;
DROP TABLE IF EXISTS employees    CASCADE;
DROP TABLE IF EXISTS customers    CASCADE;


-- ----------------------------------------------------------------------------
-- categories : a self-referencing tree (a category may have a parent category)
-- ----------------------------------------------------------------------------
CREATE TABLE categories (
    category_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name      text    NOT NULL UNIQUE,
    parent_category_id integer REFERENCES categories (category_id),
    description        text
);


-- ----------------------------------------------------------------------------
-- suppliers : who we buy products from
-- ----------------------------------------------------------------------------
CREATE TABLE suppliers (
    supplier_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name text    NOT NULL,
    country       text,
    contact_email text,
    rating        numeric(2,1) CHECK (rating >= 0 AND rating <= 5),
    active_since  date
);


-- ----------------------------------------------------------------------------
-- products : what we sell
-- ----------------------------------------------------------------------------
CREATE TABLE products (
    product_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name    text    NOT NULL,
    category_id     integer REFERENCES categories (category_id),
    supplier_id     integer REFERENCES suppliers  (supplier_id),
    price           numeric(10,2) NOT NULL CHECK (price >= 0),
    cost            numeric(10,2) CHECK (cost >= 0),
    stock_quantity  integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    weight_kg       numeric(6,3),
    is_discontinued boolean NOT NULL DEFAULT false,
    added_on        date    NOT NULL
);


-- ----------------------------------------------------------------------------
-- customers : who buys from us
-- ----------------------------------------------------------------------------
CREATE TABLE customers (
    customer_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    text NOT NULL,
    last_name     text NOT NULL,
    email         text NOT NULL UNIQUE,
    phone         text,
    city          text,
    country       text NOT NULL,
    signup_date   date NOT NULL,
    birth_date    date,
    loyalty_tier  text CHECK (loyalty_tier IN ('bronze','silver','gold','platinum')),
    is_active     boolean NOT NULL DEFAULT true
);


-- ----------------------------------------------------------------------------
-- employees : a self-referencing hierarchy (employee -> manager)
-- ----------------------------------------------------------------------------
CREATE TABLE employees (
    employee_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     text NOT NULL,
    last_name      text NOT NULL,
    email          text NOT NULL UNIQUE,
    manager_id     integer REFERENCES employees (employee_id),
    department     text NOT NULL,
    job_title      text NOT NULL,
    hire_date      date NOT NULL,
    salary         numeric(10,2) NOT NULL CHECK (salary > 0),
    commission_pct numeric(4,3)
);


-- ----------------------------------------------------------------------------
-- orders : one row per customer order
-- ----------------------------------------------------------------------------
CREATE TABLE orders (
    order_id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       integer NOT NULL REFERENCES customers (customer_id),
    employee_id       integer REFERENCES employees (employee_id),
    order_date        date NOT NULL,
    status            text NOT NULL
        CHECK (status IN ('pending','paid','shipped','delivered','cancelled','returned')),
    shipping_city     text,
    shipping_country  text,
    shipping_cost     numeric(8,2) NOT NULL DEFAULT 0
);


-- ----------------------------------------------------------------------------
-- order_items : the lines of an order (an order has 1..n items)
-- ----------------------------------------------------------------------------
CREATE TABLE order_items (
    order_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      integer NOT NULL REFERENCES orders   (order_id) ON DELETE CASCADE,
    product_id    integer NOT NULL REFERENCES products (product_id),
    quantity      integer NOT NULL CHECK (quantity > 0),
    unit_price    numeric(10,2) NOT NULL CHECK (unit_price >= 0),
    discount_pct  numeric(4,3) NOT NULL DEFAULT 0
        CHECK (discount_pct >= 0 AND discount_pct < 1),
    UNIQUE (order_id, product_id)
);


-- ----------------------------------------------------------------------------
-- payments : money received against an order (an order may have 0..n payments)
-- ----------------------------------------------------------------------------
CREATE TABLE payments (
    payment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   integer NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    paid_at    timestamptz NOT NULL,
    amount     numeric(10,2) NOT NULL CHECK (amount > 0),
    method     text NOT NULL
        CHECK (method IN ('card','paypal','bank_transfer','gift_card','cash_on_delivery')),
    status     text NOT NULL DEFAULT 'captured'
        CHECK (status IN ('captured','refunded','failed'))
);


-- ----------------------------------------------------------------------------
-- reviews : customer product reviews (a product may have 0..n reviews)
-- ----------------------------------------------------------------------------
CREATE TABLE reviews (
    review_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    integer NOT NULL REFERENCES products  (product_id) ON DELETE CASCADE,
    customer_id   integer NOT NULL REFERENCES customers (customer_id),
    rating        integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title         text,
    body          text,
    created_at    timestamptz NOT NULL,
    helpful_votes integer NOT NULL DEFAULT 0,
    UNIQUE (product_id, customer_id)
);


COMMIT;

\echo '01_schema.sql : 9 tables created.'
